// Interpret known WeChat labels as possible tone, never as proof of intent.
const HINTS: Record<string,string> = {
  旺柴:'可能是调侃、反话、试探或会意；结合整段对话，不据此认定冒犯或保证善意',
  裂开:'可能是崩溃、震惊或夸张吐槽', 捂脸:'可能是尴尬、自嘲或无奈',
  笑哭:'觉得好笑，也可能是无奈地笑', 破涕为笑:'觉得好笑，也可能是无奈地笑',
  微笑:'可能是礼貌、克制或讽刺，取决于语境', 偷笑:'可能在偷着乐或开玩笑',
  调皮:'玩笑、逗弄的可能线索', 害羞:'可能害羞或不好意思',
  白眼:'可能嫌弃、无语或熟人互损', 无语:'可能无语、尴尬或不想展开',
  嘿哈:'可能得意、玩笑或起哄', 吃瓜:'可能在围观、好奇或看热闹',
  狗头:'可能是调侃或反话', 机智:'可能得意或会意', 可怜:'可能委屈、示弱或撒娇',
  皱眉:'可能困惑、担心或不满', 叹气:'可能疲惫、失望或无奈',
  流泪:'可能难过、感动或夸张表达', 大哭:'可能强烈难过或夸张吐槽',
  发怒:'可能生气或夸张抗议', 呲牙:'可能开心或打趣', 强:'可能赞同或夸赞',
  抱拳:'可能感谢、佩服或告辞', 握手:'可能认可、合作或客气回应',
  爱心:'可能喜欢、感谢或亲近', 心碎:'可能失落、伤心或玩笑式受伤',
};
export function expressionHints(text: string) {
  return [...new Set([...text.matchAll(/\[([^\]\n]{1,12})\]/gu)].map(m=>m[1]))]
    .filter(name=>HINTS[name]).map(name=>({name,possibleMeaning:HINTS[name]}));
}
